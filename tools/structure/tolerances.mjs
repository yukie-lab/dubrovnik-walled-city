// ============================================================================
// tolerances.mjs — 許容差は「人間が気づくか」から決める。合格させるために
// 緩めてはならない。緩めた瞬間、この一式は何も証明しなくなる。
//
// 各定数には物理的な根拠を書く。根拠が書けない許容差は、許容差ではなく願望。
// ============================================================================

// ---- 接地 ---------------------------------------------------------------
// 歩行距離(1.5〜3m)で人間が段差として気づく最小は約 5mm。地面は 3.2m 格子の
// 三角形で近似しているので、フットプリントの中で地形が最大 ±2cm ずれ得る。
// 「浮き」は影が切れて即座に見えるので厳しく、「めり込み」は見えないので緩い。
export const FLOAT_MAX = 0.010;      // m. 1cm 浮くと接地影に隙間が出る
export const EMBED_MAX = 0.220;      // m. 石材 1 枚ぶん。これ以上沈むと巾木が消える

// 建物の四隅。斜面に張り出した角は、中心が正しくても浮く。
// 角は面の端なので、浮きは中心よりさらに目立つ(空が透ける)。
export const CORNER_FLOAT_MAX = 0.015;
export const CORNER_EMBED_MAX = 0.400;   // 斜面側の角は基礎で埋まってよい

// ---- 石段 ---------------------------------------------------------------
// 実測のドゥブロヴニクの路地: 蹴上 0.14〜0.20m。0.24m を超えると人は
// 「段」ではなく「よじ登る」と感じる。
export const MIN_RISE = 0.10;
export const MAX_RISE = 0.24;
// 同じ一続きの階段で、中央値から 2cm 外れる段が 1 つあれば「置き間違い」。
export const RISE_DEVIATION_MAX = 0.020;
// 踏面と蹴上の間に隙間があると、足が抜ける。段の重なりは 0 以上。
export const STEP_GAP_MAX = 0.002;

// ---- 歩行 ---------------------------------------------------------------
export const PLAYER_RADIUS = 0.30;   // m. 肩幅の半分
export const PLAYER_EYE = 1.62;      // m. 目の高さ
export const STEP_UP_MAX = 0.42;     // m. 登れる段差。膝の高さ
export const FALL_MAX = 0.60;        // m. これ以上落ちると「落下」
// 城壁の周回が閉じているか。1 周して出発点に戻る誤差。
export const CIRCUIT_CLOSE_MAX = 0.50;

// ---- 包絡(閉じた空間から空が見えるか)---------------------------------
// 4000 本のうち 1 本が漏れれば、その方向に立てば必ず見える。
export const ESCAPE_RAYS = 512;
export const ESCAPE_MAX_FRACTION = 0.0;   // 開口タグ以外からの漏れは 1 本も許さない

// ---- 当たり判定と見た目の一致 -------------------------------------------
// 見える壁をすり抜ける / 見えない壁に阻まれる、はどちらもここから出る。
// 0.25m は「肩が引っかかるが通れる」境目。
export const COLLIDER_DEVIATION_MAX = 0.25;

// ---- 相互貫入 -----------------------------------------------------------
// 石積みの目地や瓦の重なりは意図的な貫入。それ以外が 5cm 以上重なるのは事故。
export const INTERSECT_MAX = 0.05;

// ---- Z ファイティング ---------------------------------------------------
// 同一平面とみなす角度(法線のなす角 1.5 度)と、離れているとみなす距離。
// 深度バッファの精度から、近景 10m で 1mm 差は必ずちらつく。
export const COPLANAR_EPS = Math.cos(1.5 * Math.PI / 180);
export const Z_SEP_MIN = 0.004;      // m. 4mm

// ---- 立体であること -----------------------------------------------------
// 石は厚みを持つ。0.10m 未満の「石」は板であって石ではない。
export const MIN_THICKNESS = 0.10;
// 頂点を溶接して同じ点とみなす距離。生成時の丸め誤差より大きく、
// 実際の目地(4mm)より小さく。
export const WELD_EPS = 0.0015;
// 体積がこれ以下の閉多面体は退化(ぺしゃんこ)。
export const MIN_VOLUME = 1e-4;      // m^3

// ---- 街路網の一致 -------------------------------------------------------
// 同じ交差点とみなす距離。路地の幅の半分より小さく。
export const NODE_MERGE_MAX = 1.2;   // m

// 上に載せた石(狭間石など)が浮いて/埋まって見えはじめる隙間。
// 段の蹴上は 0.17〜0.21m。その半分を超えると、歩廊からは石が段に噛んで
// 「飛び出している」と読める。石工の据え付け目地は 10〜15mm なので、
// それより明確に大きい 0.10m を境にする。
export const SEAT_GAP = 0.10;
