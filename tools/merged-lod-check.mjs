import assert from 'node:assert/strict';
import * as THREE from 'three';
import {mergeGeometries} from 'three/addons/utils/BufferGeometryUtils.js';
import {MergedSolidLOD} from '../src/merged-lod.js';
const parts=[[0,0,-5],[10,0,-5],[0,0,5]].map(xyz=>new THREE.BoxGeometry(1,1,1).translate(...xyz));
const geometry=mergeGeometries(parts),mesh=new THREE.Mesh(geometry,new THREE.MeshBasicMaterial());
geometry.userData.solids=parts.map((g,i)=>({x:i,z:0,from:i*12,to:(i+1)*12}));
mesh.castShadow=true;const source=geometry.index.array.slice(),lod=new MergedSolidLOD(mesh);
const camera=new THREE.PerspectiveCamera(50,1.6,.1,100),shadow=new THREE.OrthographicCamera(9,11,1,-1,.1,20);
const frustum=new THREE.Frustum().setFromProjectionMatrix(camera.projectionMatrix),sun=new THREE.Frustum().setFromProjectionMatrix(shadow.projectionMatrix);
lod.update(frustum.planes,sun.planes);assert.equal(lod.count,72,'Keep visible house and offscreen shadow caster');
assert.deepEqual(geometry.index.array.subarray(0,72),source.subarray(0,72));
camera.rotation.y=Math.PI;camera.updateMatrixWorld();
frustum.setFromProjectionMatrix(new THREE.Matrix4().multiplyMatrices(camera.projectionMatrix,camera.matrixWorldInverse));
lod.update(frustum.planes,null);assert.equal(lod.count,36);
assert.deepEqual(geometry.index.array.subarray(0,36),source.subarray(72));
lod.update([new THREE.Plane(new THREE.Vector3(1,0,0),-1000)],null);assert.equal(lod.count,0);
lod.restore();assert.deepEqual(geometry.index.array,source);assert.equal(lod.count,108);
assert(geometry.boundingSphere.radius>5,'Whole-batch bound must survive empty draw');
console.log('Merged solids: view/shadow union, exact index identity, empty draw and restoration passed.');
